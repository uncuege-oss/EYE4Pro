using Kst.Acoustics.Core.Bina.Services;
using netDxf;
using netDxf.Entities;
using netDxf.Blocks;
using netDxf.Tables;
using netDxf.Units;
int passed = 0;
void Check(bool condition, string title) { if (!condition) throw new Exception(title); passed++; Console.WriteLine("PASS " + title); }
string folder = Path.Combine(Path.GetTempPath(), "bina-layer-tests-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(folder);
try
{
 var doc = new DxfDocument(); doc.DrawingVariables.InsUnits = DrawingUnits.Meters;
 var wall = new Layer("WALL"); var label = new Layer("LABEL"); var door = new Layer("DOOR");
 var off = new Layer("DECOR") { IsVisible = false }; var frozen = new Layer("FROZEN") { IsFrozen = true };
 var parent = new Layer("PARENT"); var child = new Layer("CHILD"); var dim = new Layer("DIM");
 Polyline2D Box(double x, Layer layer) => new(new[] { new Vector2(x,0), new Vector2(x+10,0), new Vector2(x+10,8), new Vector2(x,8) }, true) { Layer = layer };
 doc.Entities.Add(Box(0, wall)); doc.Entities.Add(Box(50, off)); doc.Entities.Add(Box(100, frozen)); doc.Entities.Add(Box(150, dim));
 doc.Entities.Add(new Text("OKUMA SALONU", new Vector2(5,4),.3) { Layer = label });
 doc.Entities.Add(new Text("NOISE ROOM", new Vector2(55,4),.3) { Layer = off });
 doc.Entities.Add(new Arc(new Vector2(2,0),.9,0,90) { Layer = door });
 var nested = new Block("NESTED"); nested.Entities.Add(new Line(new Vector2(0,0), new Vector2(2,0)));
 var block = new Block("BLOCK");
 block.Entities.Add(new Line(new Vector2(0,0),new Vector2(3,0)));
 block.Entities.Add(new Line(new Vector2(0,1),new Vector2(4,1)) { Layer = child });
 block.Entities.Add(new Text("INHERITED NAME",new Vector2(0,2),.3));
 block.Entities.Add(new Insert(nested,new Vector2(0,3)));
 var attributeDef = new AttributeDefinition("ROOM") { Value = "ATTR ROOM", Position = new Vector3(1,2,0), Height = .3 };
 block.AttributeDefinitions.Add(attributeDef);
 var insert = new Insert(block,new Vector2(20,20)) { Layer = parent, Rotation = 90 };
 insert.Attributes.First().Value = "ATTR ROOM"; insert.TransformAttributes();
 doc.Entities.Add(insert);
 string path = Path.Combine(folder,"layers.dxf"); doc.Save(path);
 var drawing = new DxfKatPlaniParser().KatmanliOku(path);
 var defaults = drawing.Katmanlar.Where(k=>k.VarsayilanAcik).Select(k=>k.Ad).ToList();
 Check(!defaults.Contains("DECOR") && !defaults.Contains("FROZEN"), "CAD off/frozen defaults");
 Check(drawing.Katmanlar.Single(k=>k.Ad=="WALL").NesneSayisi == 1, "Entity counts are not tessellation counts");
 var preview = drawing.HamKatOlustur(defaults);
 Check(preview.Odalar.Count == 0 && preview.Acikliklar.Count == 0, "Loading and preview never produce rooms");
 Check(preview.HamMetinler.All(t=>t.Value!="NOISE ROOM"), "Hidden labels excluded");
 Check(preview.HamSegmentler.All(s=>s.A.X<50 || s.A.X>=150), "Hidden/frozen geometry excluded");
 Check(preview.DxfArclar.Count == 1, "Visible arcs retained");
 var noDoor = drawing.HamKatOlustur(defaults.Where(x=>x!="DOOR"));
 Check(noDoor.DxfArclar.Count==0 && noDoor.HamSegmentler.Count < preview.HamSegmentler.Count, "Closing arc layer removes geometry and detection arcs");
 var noParent = drawing.HamKatOlustur(defaults.Where(x=>x!="PARENT"));
 Check(noParent.HamMetinler.All(t=>t.Value!="INHERITED NAME" && t.Value!="ATTR ROOM"), "Parent closure hides inherited texts and attributes");
 Check(noParent.HamSegmentler.All(s=>s.A.X<15 || s.A.X>30), "Parent closure hides nonzero-layer nested children");
 var parentOnly = drawing.HamKatOlustur(new[] { "PARENT" });
 Check(parentOnly.HamSegmentler.Count==2, "Layer zero geometry inherits insert and nested layer");
 Check(parentOnly.HamMetinler.Count==2, "Layer zero text and attribute inherit parent without zero checkbox");
 Check(parentOnly.HamSegmentler.Any(s=>Math.Abs(s.A.X-20)<.001 && Math.Abs(s.B.Y-23)<.001), "Block rotation and translation retained");
 var childClosed = drawing.HamKatOlustur(defaults.Where(x=>x!="CHILD"));
 Check(childClosed.HamSegmentler.Count == preview.HamSegmentler.Count - 1, "Closing explicit child layer retains other block contents");
 var selected = drawing.HamKatOlustur(new[] { "wall", "label" });
 Check(selected.HamSegmentler.Count==4 && selected.HamMetinler.Count==1, "Case insensitive exact layer selection");
 selected.HamSegmentler.Clear();
 Check(drawing.HamKatOlustur(new[] {"WALL"}).HamSegmentler.Count==4, "Preview snapshots cannot modify source cache");
 var snapshot = drawing.HamKatOlustur(new[]{"WALL","LABEL"});
 File.Delete(path);
 var result = new DxfKatYukleyici().OtomatikYukle(snapshot);
 Check(result.Katlar.Count==1 && result.Katlar[0].Odalar.Any(o=>o.Ad=="OKUMA SALONU"), "Generate from filtered snapshot without reopening deleted CAD");
 Check(result.Katlar[0].KaynakKatmanlari!.SequenceEqual(new[]{"LABEL","WALL"}), "Selection carried into generated floor");
 Check(result.Katlar[0].KayitliTespitSegmentleri?.Count==4, "Detection geometry persisted after normalization");
 var empty = drawing.HamKatOlustur(Array.Empty<string>());
 Check(empty.HamSegmentler.Count==0 && empty.HamMetinler.Count==0 && empty.DxfArclar.Count==0, "All layers off is empty");
 Check(new DxfKatYukleyici().OtomatikYukle(empty).Katlar.Count==0, "All layers off cannot fall back to source");
 var annotationOnly = drawing.HamKatOlustur(new[]{"DIM"});
 var annotationResult = new DxfKatYukleyici().OtomatikYukle(annotationOnly);
 Check(annotationResult.Katlar.All(k=>k.Odalar.Count==0 && k.Acikliklar.Count==0), "Explicit empty detection cannot fall back to annotation lines");
 var single = new DxfKatYukleyici().Yukle(snapshot,3,"Selected",4.2);
 Check(single.KatNo==3 && single.Ad=="Selected" && single.KatYuksekligiM==4.2 && single.Odalar.Count==1, "Selected-floor overload uses same filtered snapshot");
}
finally { Directory.Delete(folder,true); }
passed += AnnotationArcTests.Run();
passed += KotMetadataTests.Run();
passed += AppRegistryXDataTests.Run();
Console.WriteLine($"{passed}/{passed} passed");
