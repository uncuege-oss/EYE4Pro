public record MetrajColor(short Aci, byte? R = null, byte? G = null, byte? B = null)
{
    public bool IsByLayer => Aci == 256;
    public bool IsByBlock => Aci == 0;
}

public record MetrajPoint(double X, double Y, double Z);

public class MetrajPointComparer : IEqualityComparer<MetrajPoint>
{
    private readonly double _tolerance;
    public MetrajPointComparer(double tolerance = 1e-6) => _tolerance = tolerance;

    public bool Equals(MetrajPoint? p1, MetrajPoint? p2)
    {
        if (p1 == null || p2 == null) return p1 == p2;
        return Math.Abs(p1.X - p2.X) < _tolerance &&
               Math.Abs(p1.Y - p2.Y) < _tolerance &&
               Math.Abs(p1.Z - p2.Z) < _tolerance;
    }

    public int GetHashCode(MetrajPoint obj)
    {
        // Use a slightly larger quantization for hashing to reduce boundary issues, 
        // though fuzzy hashing is never 100% perfect for Dictionary keys.
        double hTol = _tolerance * 100.0; 
        return HashCode.Combine(
            (int)Math.Round(obj.X / hTol),
            (int)Math.Round(obj.Y / hTol),
            (int)Math.Round(obj.Z / hTol)
        );
    }
}

public abstract record MetrajEntity(
    MetrajEntityType Type,
    string Layer,
    MetrajColor Color,
    MetrajPoint? InsertionPoint = null
)
{
    public MetrajColor EffectiveColor { get; set; } = Color;
    // True when this entity was generated by expanding a block insert.
    // Used to avoid double-counting with BlockCounter.
    public bool IsFromBlock { get; set; } = false;
}

public record MetrajLine(string Layer, MetrajColor Color, MetrajPoint Start, MetrajPoint End) 
    : MetrajEntity(MetrajEntityType.Line, Layer, Color);

public record MetrajPolyline(string Layer, MetrajColor Color, List<MetrajPoint> Vertices, bool IsClosed) 
    : MetrajEntity(MetrajEntityType.Polyline, Layer, Color);

public record MetrajArc(string Layer, MetrajColor Color, MetrajPoint Center, double Radius, double StartAngle, double EndAngle) 
    : MetrajEntity(MetrajEntityType.Arc, Layer, Color);

public record MetrajCircle(string Layer, MetrajColor Color, MetrajPoint Center, double Radius) 
    : MetrajEntity(MetrajEntityType.Circle, Layer, Color);

public record MetrajEllipse(string Layer, MetrajColor Color, MetrajPoint Center, double MajorAxisX, double MajorAxisY, double MajorAxisZ, double Ratio, double StartAngle, double EndAngle) 
    : MetrajEntity(MetrajEntityType.Ellipse, Layer, Color);

public record BlockCountKey(string BlockName, string LayerName, MetrajColor Color, string AttributesHash);

public record MetrajText(string Layer, MetrajColor Color, string Value, MetrajPoint Position) 
    : MetrajEntity(MetrajEntityType.Text, Layer, Color, Position);

public record MetrajMText(string Layer, MetrajColor Color, string Value, MetrajPoint Position) 
    : MetrajEntity(MetrajEntityType.MText, Layer, Color, Position);

public record MetrajInsert(string Layer, MetrajColor Color, string BlockName, MetrajPoint Position, Dictionary<string, string>? Attributes = null) 
    : MetrajEntity(MetrajEntityType.Insert, Layer, Color, Position);

// Not: Spline için basitlik adına kontrol noktaları tutulabilir.
public record MetrajSpline(string Layer, MetrajColor Color, List<MetrajPoint> ControlPoints) 
    : MetrajEntity(MetrajEntityType.Spline, Layer, Color);

public class MetrajProject
{
    public List<MetrajEntity> Entities { get; set; } = new();
    public List<MetrajInsert> AllInserts { get; set; } = new(); // Flattened for BlockCounter
    public string Name { get; set; } = string.Empty;
    public MetrajSourceUnit SourceUnit { get; set; } = MetrajSourceUnit.Millimeters;
    /// <summary>Block name → geometry entities of that block definition (un-transformed)</summary>
    public Dictionary<string, List<MetrajEntity>> BlockDefinitions { get; set; } = new();
}
